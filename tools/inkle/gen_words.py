#!/usr/bin/env python3
"""Generate src/apps_local/inkle/InkleWords.cpp from SCOWL word lists.

Usage:
  python3 tools/inkle/gen_words.py /path/to/scowl-2020.12.07/final

SCOWL (Spell Checking Oriented Word Lists) by Kevin Atkinson, http://wordlist.aspell.net/,
is distributed under a permissive license that allows use, modification and
redistribution with attribution (see SCOWL's README). We use two tiers:

  ANSWERS : five-letter words from english-/american-words.{10,20,35}
            (the common tiers), minus plural-looking words, minus a short deny list.
  ALLOWED : five-letter words from english-/american-words.{10..70}, plus ANSWERS.

Both lists are lowercase a-z only, sorted, and emitted as packed 5-byte records so
the firmware can binary-search them without any per-word pointers.
"""
import os
import re
import sys

ANSWER_TIERS = (10, 20, 35)
ALLOWED_TIERS = (10, 20, 35, 40, 50, 55, 60, 70)
PREFIXES = ("english", "american")
FIVE = re.compile(r"[a-z]{5}")

# Words that are valid guesses but should never be the day's answer.
DENY_ANSWERS = {
    "bitch", "whore", "pussy", "penis", "boobs", "boner", "cocks", "dicks", "cunts",
    "slurs", "nazis", "rapes", "raped", "porno", "porns", "semen", "sperm", "fecal",
    "feces", "urine", "vomit", "queer", "dildo", "negro", "spick", "kikes", "gooks",
}


def load(final_dir, name):
    path = os.path.join(final_dir, name)
    if not os.path.exists(path):
        return set()
    with open(path, encoding="latin-1") as fh:
        return {line.strip() for line in fh}


def five_letter(words):
    return {w for w in words if FIVE.fullmatch(w)}


def tier_words(final_dir, tiers):
    out = set()
    for tier in tiers:
        for prefix in PREFIXES:
            out |= five_letter(load(final_dir, f"{prefix}-words.{tier}"))
    return out


def looks_plural(word, all_words):
    # "laces" -> "lace", "malts" -> "malt"; keep "glass", "chess" (double s).
    if not word.endswith("s") or word.endswith("ss"):
        return False
    stem = word[:-1]
    return stem in all_words or (stem + "e") in all_words or (word.endswith("es") and word[:-2] in all_words)


def emit(path, answers, allowed, source_note):
    def packed(words):
        lines = []
        for i in range(0, len(words), 12):
            chunk = words[i:i + 12]
            lines.append("    " + " ".join(f'"{w}"' for w in chunk))
        return "\n".join(lines)

    with open(path, "w", encoding="ascii") as fh:
        fh.write(
            "// GENERATED by tools/inkle/gen_words.py -- do not edit by hand.\n"
            f"// Source: {source_note}\n"
            "// SCOWL is Copyright 2000-2018 Kevin Atkinson; used and redistributed under its\n"
            "// permissive license (see tools/inkle/SCOWL-LICENSE.txt).\n"
            "#include \"InkleWords.h\"\n\n"
            "namespace inkle {\n\n"
            f"const size_t ANSWER_COUNT = {len(answers)};\n"
            f"const size_t ALLOWED_COUNT = {len(allowed)};\n\n"
            "// Each entry is exactly 5 letters; string literals concatenate into one flat array.\n"
            "const char ANSWERS[] =\n"
            + packed(answers)
            + ";\n\nconst char ALLOWED[] =\n"
            + packed(allowed)
            + ";\n\n}  // namespace inkle\n"
        )


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(2)
    final_dir = sys.argv[1]
    here = os.path.dirname(os.path.abspath(__file__))
    out_path = os.path.normpath(os.path.join(here, "..", "..", "src", "apps_local", "inkle", "InkleWords.cpp"))

    allowed_all = tier_words(final_dir, ALLOWED_TIERS)
    # Full dictionary (any length) for plural detection.
    everything = set()
    for tier in ALLOWED_TIERS:
        for prefix in PREFIXES:
            everything |= load(final_dir, f"{prefix}-words.{tier}")

    answers = {
        w for w in tier_words(final_dir, ANSWER_TIERS)
        if w not in DENY_ANSWERS and not looks_plural(w, everything)
    }
    allowed = sorted(allowed_all | answers)
    answers = sorted(answers)

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    emit(out_path, answers, allowed, f"SCOWL final/ lists, tiers {ANSWER_TIERS} for answers, {ALLOWED_TIERS} for guesses")
    print(f"answers={len(answers)} allowed={len(allowed)} -> {out_path}")


if __name__ == "__main__":
    main()
